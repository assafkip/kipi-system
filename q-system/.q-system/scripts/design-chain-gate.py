def outside_inputs_that_differ(snap) -> list[str]:
    """The census again, against the live tree now: what differs from what this seal held."""
    raw = None
    if snap.cfg_live is not None and snap.cfg_live.is_file():
        raw = snap.cfg_live.read_bytes()
    now, _ = _outside_inputs(snap.root, snap.live, snap.files, snap.cfg, snap.cfg_live, raw, judge=False)
    return sorted(k for k in set(snap.inputs) | set(now) if snap.inputs.get(k) != now.get(k))


@contextlib.contextmanager
def snapshot_round(rd: Path, cfg_path: Path | None = None):
    if rd.resolve() in _SNAPSHOTS:
        # Two seals sharing one entry: the first to finish pops it and the other's producers
        # quietly take a snapshot of their own (standard review of 4ab043d7). An OSError, so
        # it is a refusal like every other.
        raise BlockingIOError(f"a seal of {rd} is already running in this process")
    files = round_files(rd)
    tmp = Path(tempfile.mkdtemp(prefix="dc-seal-"))          # mkdtemp is mode 0700
    try:
        root = tmp / "held"
        cfg: dict = {}
        raw = None
        if cfg_path is not None:
            raw = cfg_path.read_bytes()                      # read ONCE: producers and chain share it
            try:
                cfg = json.loads(raw)
            except ValueError:
                cfg = {}
            cfg = cfg if isinstance(cfg, dict) else {}
        inputs, sources = _outside_inputs(root, rd, files, cfg, cfg_path, raw)
        for key, data in inputs.items():
            dest = _held_path(root, Path(key.rstrip(os.sep) or os.sep))
            if key.endswith(os.sep):
                dest.mkdir(parents=True, exist_ok=True)
            elif data is not None:
                dest.parent.mkdir(parents=True, exist_ok=True)
                dest.write_bytes(data)
        snap_dir = _held_path(root, rd)
        for rel, data in files.items():                      # last, so the round's own bytes win
            dest = snap_dir / rel
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_bytes(data)
        snap_dir.mkdir(parents=True, exist_ok=True)
        snap = RoundSnapshot(rd, files, snap_dir, root)
        snap.cfg_path = _held_path(root, cfg_path) if cfg_path is not None else None
        snap.cfg, snap.sources, snap.inputs, snap.cfg_live = cfg, sources, inputs, cfg_path
        _SNAPSHOTS[rd.resolve()] = snap
        yield snap
    finally:
        _SNAPSHOTS.pop(rd.resolve(), None)
        shutil.rmtree(tmp, ignore_errors=True)


@contextlib.contextmanager
def served_round(rd: Path, files: dict[str, bytes] | None = None, missed: list[str] | None = None):
    """Serve the round on a loopback port the OS picks, for the length of one seal.

    Nothing owned the server before: the command doc backgrounded one on a typed port and
    never stopped it. A leftover from an earlier round kept the port, the new bind failed
    silently, and the standard producer measured the OLD round over the URL while writing
    the sha of the NEW local file (PRD finding-3). Port 0 cannot collide, the server dies in
    the finally, and each producer refuses when the served bytes differ from the local file.

    ASK-1808: it serves `files`, bytes read once and held in memory. It used to read the disk
    on every GET, which is what let a file be one thing for the browser and another for both
    of seal's checks."""
    held = round_files(rd) if files is None else files

    class Held(http.server.BaseHTTPRequestHandler):
        """Files of the round, and nothing else: no listing, nothing outside it."""

        def _answer(self, body: bool):
            path = urllib.parse.unquote(urllib.parse.urlsplit(self.path).path)
            rel = posixpath.normpath(path).lstrip("/")
            data = held.get(rel)
            if data is None:
                if missed is not None and rel not in missed:
                    missed.append(rel)
                self.send_error(404, "not a file in this round")
                return
            ctype = mimetypes.guess_type(rel)[0] or "application/octet-stream"
            if ctype.startswith("text/") or ctype in ("application/javascript", "application/json", "image/svg+xml"):
                # No charset made chromium decode a UTF-8 page as windows-1252 and then ask for
                # a mojibake stylesheet name, which 404ed, and the page PASSED on the browser's
                # 16px default (adversarial review of 4ab043d7, spy server output pasted there).
                ctype += "; charset=utf-8"
            self.send_response(200)
            self.send_header("Content-Type", ctype)
            self.send_header("Content-Length", str(len(data)))
            self.send_header("Cache-Control", "no-store")
            self.end_headers()
            if body:
                self.wfile.write(data)

        def do_GET(self):
            self._answer(True)

        def do_HEAD(self):
            self._answer(False)

        def log_message(self, *args):
            pass
    srv = http.server.ThreadingHTTPServer(("127.0.0.1", 0), Held)
    thread = threading.Thread(target=srv.serve_forever, kwargs={"poll_interval": 0.02}, daemon=True)
    thread.start()
    try:
        yield f"http://127.0.0.1:{srv.server_address[1]}"
    finally:
        srv.shutdown()
        srv.server_close()
        thread.join(timeout=5)


def _read_standard(std_path: Path) -> list:
    try:
        data = json.loads(std_path.read_text())
    except (OSError, ValueError):
        return []
    return [e for e in (data if isinstance(data, list) else [data]) if isinstance(e, dict)]


def _drop_prior_verdict(std_path: Path, page: Path) -> None:
    """Remove THIS page's entry before the producer runs, so an entry afterwards can only
    have been written by this run. dc-02 inferred freshness from st_mtime_ns strictly
    increasing, which is an assumption about the filesystem (wrong in principle at 1-second
    granularity). Owning the output file needs no assumption. Other pages' entries stay."""
    if not std_path.is_file():
        return
    entries = _read_standard(std_path)
    kept = [e for e in entries if e.get("page") != page.name]
    if len(kept) != len(entries):
        std_path.write_text(json.dumps(kept, indent=2) + "\n")


def _fresh_standard_entry(std_path: Path, page: Path, cur: str | None = None) -> dict | None:
    """The entry the producer wrote for THIS page during THIS run, or None. An exit code is a
    claim; the verdict is the entry, and it has to carry this page's bytes: `cur`, the sha of
    the bytes seal holds in memory (ASK-1808), else the file as it stands."""
    cur = cur or sha(page)
    for e in _read_standard(std_path):
        if e.get("page") == page.name and e.get("sha256") == cur:
            return e
    return None


def round_declaration(rd: Path) -> dict:
    """The round's craft-manifest.json. While a seal holds a snapshot of this round, the
    SNAPSHOT's: a wireframe declaration that existed on disk only while seal was running
    skipped the gap producer and the round sealed, with no manifest on disk before or after
    (adversarial review of 4ab043d7)."""
    held = _SNAPSHOTS.get(rd.resolve())
    if held is not None:
        raw = held.files.get(CRAFT_MANIFEST)
        if raw is None:
            return {}
        text = raw.decode("utf-8", "replace")
    else:
        mp = rd / CRAFT_MANIFEST
        if not mp.is_file():
            return {}
        text = mp.read_text()
    try:
        d = json.loads(text)
    except ValueError:
        return {}
    return d if isinstance(d, dict) else {}


def producer_problems(rd: Path, pages: list[Path], cfg: dict) -> list[tuple[str, list[str]]]:
    """Run the producers for a round against a snapshot and a server this call owns. Returns
    (name, problems) pairs in seal's `bad` shape. seal holds the snapshot so it can compare the
    live round to it afterwards; a direct call takes its own."""
    try:
        held = _SNAPSHOTS.get(rd.resolve())
        if held is not None:
            return _run_producers(held, pages, cfg)
        with snapshot_round(rd, load_config(pages[0])[1] if pages else None) as snap:
            return _run_producers(snap, pages, cfg)
    except OSError as e:
        # No loopback, no file descriptors, a read-only standard.json or checks/. Every other
        # producer failure refuses with exit 2; a traceback and exit 1 is a code nobody defined.
        return [("seal", [f"could not measure: {type(e).__name__}: {e}"])]


def _copy_back(snap: RoundSnapshot, rel: str) -> None:
    """A verdict the producer wrote in the snapshot goes back to the round, pass or fail. A
    verdict that was NOT written removes the round's old one: only this run may speak."""
    src, dest = snap.dir / rel, snap.live / rel
    if src.is_file():
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_bytes(src.read_bytes())
    else:
        dest.unlink(missing_ok=True)


def _run_producers(snap: RoundSnapshot, pages: list[Path], cfg: dict) -> list[tuple[str, list[str]]]:
    bad: list[tuple[str, list[str]]] = []
    rd = snap.live
    timeout, why = producer_timeout(cfg)
    if why:
        return [("seal", [why])]

    def timed(stage: str, label: str, name: str, args: list[str]) -> tuple[int, str]:
        # one line per stage run, so a slow seal says where its time went (dc-05)
        t0 = time.monotonic()
        rc, tail = run_producer(name, args, timeout, stage)
        print(f"stage {stage} {label}: {time.monotonic() - t0:.2f}s (exit {rc})")
        return rc, tail
    std_path = snap.dir / "standard.json"
    # The producers find design-chain.json and references/ by walking up from the round, so
    # both are handed over by path: the HELD copies (ASK-1831), the bytes the chain reads too.
    # Resolving the config a second time here reached a DIFFERENT file through a symlinked
    # parent (canon 30 by the typed path, 5 by the resolved one).
    cfg_path = snap.cfg_path
    # only what the compare AND the digest bind: a page fetched CSS it had hidden in standard.json,
    # which seal overwrites and both skip, and a 9px page sealed COMPLETE (ASK-1838)
    with served_round(rd, served_files(snap.files), snap.missed) as base:
        for p in pages:
            sp = snap.dir / p.name
            _drop_prior_verdict(std_path, sp)
            args = [str(sp), "--url", f"{base}/{urllib.parse.quote(p.name)}"]
            if cfg_path:
                args += ["--config", str(cfg_path)]
            rc, tail = timed("standard", p.name, STANDARD_PRODUCER, args)
            snap.stages.setdefault(p.name, []).append(stage_record("standard", STANDARD_PRODUCER, rd, rc))
            entry = _fresh_standard_entry(std_path, sp, snap.sha(p.name))
            _copy_back(snap, "standard.json")
            if rc == 0 and entry and entry.get("pass") is True:
                continue
            if rc == 1 and entry and entry.get("pass") is False:
                bad.append((p.name, [f"{STANDARD_PRODUCER} measured this page and it FAILS the standard: {tail}"]))
            else:
                # exit 2, a crash (also exit 1), or an exit code with no fresh verdict behind it
                bad.append((p.name, [f"could not measure ({STANDARD_PRODUCER} exit {rc}, "
                                     f"{'no' if not entry else 'a contradicting'} fresh verdict for this page): {tail}"]))
        craft = cfg.get("craft") or {}
        declared = round_declaration(rd)
        # The same round-local opt-out craft_problems() honors: a declared wireframe round carries
        # a written reason and is exempt from the craft bar. Measuring it anyway leaves it stuck.
        round_is_wireframe = declared.get("tier") == "wireframe" and str(declared.get("reason", "")).strip()
        if (craft.get("require_gap_check") and craft.get("tier", "craft") != "wireframe"
                and not round_is_wireframe):
            gap_rel = f"checks/{GAP_CHECK}"
            gap_path = snap.dir / gap_rel
            gap_path.unlink(missing_ok=True)          # same rule: only this run may write it
            gap_path.parent.mkdir(parents=True, exist_ok=True)
            rc, tail = timed("gap", rd.name, GAP_PRODUCER, [str(snap.dir), "--write", "--url-base", base,
                                                   "--refs", str(_held_path(snap.root, rd.parent / "references"))])
            snap.stages.setdefault("", []).append(stage_record("gap", GAP_PRODUCER, rd, rc))
            _copy_back(snap, gap_rel)
            if rc == 0 and not gap_path.is_file():
                bad.append((GAP_PRODUCER, [f"could not measure ({GAP_PRODUCER} exit 0 and wrote no {GAP_CHECK}): {tail}"]))
            elif rc == 2:
                # dc-03 gave the producer an exit code of its own for could-not-measure, so 2
                # means one thing. craft_problems() lists the axes per page below this line.
                bad.append((GAP_PRODUCER, [f"below the exemplar floor ({GAP_PRODUCER} exit 2): {tail}"]))
            elif rc != 0:
                bad.append((GAP_PRODUCER, [f"could not measure ({GAP_PRODUCER} exit {rc}): {tail}"]))
        # dc-04: seal RUNS the anti-pattern producer and reads its exit code. The gate used to
        # read only that checks/impeccable.txt was non-empty, so any text sealed ("ran" did),
        # and the producer exited 0 on a flagged page whenever its control fired.
        if (craft.get("require_impeccable") and craft.get("tier", "craft") != "wireframe"
                and not round_is_wireframe):
            imp_rel = f"checks/{IMPECCABLE_CHECK}"
            imp_path = snap.dir / imp_rel
            imp_path.unlink(missing_ok=True)          # only this run may write it
            imp_path.parent.mkdir(parents=True, exist_ok=True)
            # every page this seal seals, by name: the producer refuses one it cannot scan and
            # one it was not handed (review of d0492b36, finding-2)
            rc, tail = timed("impeccable", rd.name, IMPECCABLE_PRODUCER, [str(snap.dir), "--url-base", base,
                                                          *[x for p in pages for x in ("--page", p.name)]])
            snap.stages.setdefault("", []).append(stage_record("impeccable", IMPECCABLE_PRODUCER, rd, rc))
            _copy_back(snap, imp_rel)
            if rc == 0 and not imp_path.is_file():
                bad.append((IMPECCABLE_PRODUCER, [f"could not measure ({IMPECCABLE_PRODUCER} exit 0 and wrote no {IMPECCABLE_CHECK}): {tail}"]))
            elif rc == 1:
                bad.append((IMPECCABLE_PRODUCER, [f"its negative control did not fire ({IMPECCABLE_PRODUCER} exit 1), so a clean result proves nothing: {tail}"]))
            elif rc == 3:
                bad.append((IMPECCABLE_PRODUCER, [f"a page raised an anti-pattern ({IMPECCABLE_PRODUCER} exit 3): {tail}"]))
            elif rc != 0:
                bad.append((IMPECCABLE_PRODUCER, [f"could not measure ({IMPECCABLE_PRODUCER} exit {rc}): {tail}"]))
    unserved = sorted(m for m in snap.missed if m not in BROWSER_ASKS_UNPROMPTED)
    if unserved:
        bad.append(("seal", [f"the page asked for {unserved} and this round does not serve it, so the "
                             f"verdict would be about a page missing that file, not about the page. "
                             f"Add the file to the round or remove the reference. (A link outside the "
                             f"round, a name whose case differs from the file, and a symlink out of "
                             f"the round all land here.)"]))
    return bad


# What a browser requests on its own, without the page asking. Exact names; never a directory,
# never a suffix; it grows by an issue. Anything else a page asks for and does not get means
# chromium rendered a different page than the round's: a 404 stylesheet left 16px browser
# default text, which PASSES a 15px floor (adversarial review of 4ab043d7, three ways in).
BROWSER_ASKS_UNPROMPTED = frozenset({
    "favicon.ico", "apple-touch-icon.png", "apple-touch-icon-precomposed.png", "robots.txt",
})


# What the digest leaves out: the files the GATE itself writes during a seal (_SEAL_WRITES, below)
# and after one (corrections.jsonl, written by `correct`, which shape-checks every line against the
# committed page). Nothing else. By exact path, never a directory, never a suffix: a digest that
# skipped checks/ and gate/ wholesale let a stylesheet under gate/ be swapped after the seal
# (final review of c3607e0d). dc-10: the list used to be every chain record, so brief.md, the
# critique or the craft manifest could be rewritten after the seal and the round still read
# COMPLETE; now an edit to any of them opens the round.
def asset_digest(files: dict[str, bytes]) -> str:
    h = hashlib.sha256()
    for rel in sorted(files):
        # the pages themselves are left out: each carries its own sha in the receipt, and a
        # wording correction to one page must not open every other page in the round (dc-10)
        if rel not in _DIGEST_SKIP and not ("/" not in rel and Path(rel).suffix.lower() in PAGE_EXTS):
            h.update(rel.encode() + b"\x00" + files[rel] + b"\x1f")
    return h.hexdigest()


def round_asset_digest(rd: Path) -> str:
    """One sha256 over every file in the round except what the gate itself writes.

    The byte proof covered the HTML only, and the verdict is almost entirely a function of the
    CSS: measure with one shared.css, swap it, and every sha still matched while an honest
    re-measure FAILED (adversarial review of 4998d7b7). Sana, 2026-09-18: one digest, computed
    and written by seal; dc-10 makes the passive gate recompute it. It goes stale on an unused
    asset too, which is correct: COMPLETE means unedited. A playwright response hook was
    refused, because it records what chromium chose to request, which is a subset."""
    return asset_digest(round_files(rd))


# Two lists for two jobs. _SEAL_WRITES is what the live-vs-snapshot COMPARE leaves out: only
# the files this seal itself writes while it runs. _DIGEST_SKIP is what the DIGEST leaves out:
# those, plus what the gate writes after a seal. They are kept apart on purpose (Sana,
# 2026-09-19): the compare once borrowed the digest's list, so brief.md could be swapped under
# a running seal and left swapped.
_SEAL_WRITES = frozenset({"standard.json", f"checks/{GAP_CHECK}", f"checks/{IMPECCABLE_CHECK}", "receipts.json"})
_DIGEST_SKIP = _SEAL_WRITES | {"corrections.jsonl"}
# Files a browser may be shown by a seal, and file types a built site hands a browser.
WEB_SUFFIXES = {".html", ".htm", ".css", ".js", ".mjs", ".svg"}


def served_files(files: dict[str, bytes]) -> dict[str, bytes]:
    """The round a browser is shown: every file except the ones the seal writes or skips, so a 404
    for them lands in seal's unserved refusal. The reader gate loads this list from here."""
    return {rel: b for rel, b in files.items() if rel not in _DIGEST_SKIP}


def unbound_references(files: dict[str, bytes]) -> dict[str, list[str]]:
    """{web file: [skipped paths its bytes name]}. A 404 at seal time is not enough: the built
    site ships the round, so a visitor's fetch of standard.json would succeed (Sana, ASK-1838).

    A TRIPWIRE, not the guard. A text scan cannot see a path built at runtime ('stand'+'ard.json'),
    escaped, entity-encoded, or hidden between a "/*" and a "*/" inside two strings, and a fetch
    that runs only on a click or off the seal's host never reaches the seal's 404 either (review
    of eb2a48d4, std-1 and adv-3). What holds for visitors is the build leaving these files out,
    which is ASK-1839."""
    out = {}
    for rel, data in files.items():
        if Path(rel).suffix.lower() in WEB_SUFFIXES:
            # comments are not references: 8 real consulting stylesheets explain a choice with
            # "(checks/gap.json)" inside /* */ (measured 2026-09-19 over 6660 web files)
            code = re.sub(rb"/\*.*?\*/|<!--.*?-->", b" ", data, flags=re.S)
            code = re.sub(rb"(?m)(^|[\s;{}])//[^\n]*", rb"\1", code)
            # a whole path, not a substring: blog/receipts.json, nonstandard.json and a CDN's
            # .../assets/standard.json are other files (review of eb2a48d4, adv-1 and std-2)
            named = sorted(p for p in _DIGEST_SKIP
                           if re.search(rb"(?<![\w./-])(?:\.{1,2}/|/)?" + re.escape(p.encode()) + rb"(?![\w-])", code))
            if named:
                out[rel] = named
    return out


def skipped_aliases(rd: Path, files: dict[str, bytes]) -> dict[str, str]:
    """{round file: the skipped file it IS}. Bound by file identity, not by name: a symlink
    style.css -> receipts.json, a hard link, or Receipts.json on a case-insensitive disk served
    a skipped file's bytes under a name the seal does not skip, and the seal's own receipt write
    then changed what that name serves (review of eb2a48d4, adv-2)."""
    ids = {}
    for s in _DIGEST_SKIP:
        try:
            st = os.stat(rd / s)
        except OSError:
            continue
        ids[(st.st_dev, st.st_ino)] = s
    out = {}
    for rel in files:
        if rel in _DIGEST_SKIP:
            continue
        try:
            st = os.stat(rd / rel)
        except OSError:
            continue
        if (st.st_dev, st.st_ino) in ids:
            out[rel] = ids[(st.st_dev, st.st_ino)]
    return out


def files_that_differ(a: dict[str, bytes], b: dict[str, bytes]) -> list[str]:
    return sorted(rel for rel in set(a) | set(b) if rel not in _SEAL_WRITES and a.get(rel) != b.get(rel))


