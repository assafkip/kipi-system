#!/usr/bin/env python3
"""design-chain-gate: web design work cannot be shown, tested, sent or left behind
until the agreed design steps have produced their receipts.

WHY (founder, 2026-09-15, after two rounds of first screens ignored the canon):
  "When I try to create web design, you continuously find ways to go back to your
  generic stuff. If it's not reading the prose, ignoring the prose, or going around it."
  A lint on the page is a blocklist and was rejected. This is the other shape: a
  chain of receipts the harness demands before the next tool call can happen.

THE THREE HOLES THIS CLOSES (each one was used the same day):
  1. Pages generated by a script (build2.py wrote six .html files) never hit the
     Write hook. So the ledger is fed by a filesystem scan after every Bash call,
     not by the Write tool alone.
  2. Pages built outside design-room/ never hit publish_gate. So there is no path
     scope: any page file anywhere (except the internal allowlist) is in scope.
  3. A brief written from memory is how the generic layout comes back. So the brief
     must contain lines extracted LIVE from the owner files, verbatim.

WHAT IT DOES NOT BLOCK (2026-09-15): the chain's own steps. Measuring, serving,
screenshotting and sealing a page are how the chain CLOSES; blocking them made the
command unrunnable. See BASH_SHOW_RE below.

THE CHAIN, per page, in the round directory that holds the page:
  brief.md        verbatim anchors from the owner files + the three-line brief
  directions.md   three directions; cites an exemplar when exemplars/ is non-empty
  standard.json   written by design-standard-check.py: pass true, sha256 of the page
  critique.md     the nine DNA questions answered per direction
  proof.md        each artifact's proof kind and its INDEX record
  checks/         bio_gate + voice-lint outputs
  gate/           ICP-persona comprehension answers
  receipts.json   written by `seal`; sha256 per page; stale on any later edit

HOOK CONTRACT: reads the hook JSON on stdin, keys on hook_event_name and tool_name.
exit 0 = pass, exit 2 = block (stderr goes to the model). `seal` and `status` are CLI
subcommands. Fails OPEN only when the payload itself is unreadable; every ambiguity
about a page in the ledger fails CLOSED.

OVERRIDE: DESIGN_CHAIN_ALLOW=1 in the founder's shell. No in-file marker exists, on
purpose: a marker the agent can write is not an override, it is a hole.

HONEST BOUNDARY: the scan after a Bash call covers the Bash cwd, the project dir, the
scratchpad and the registered instance roots. A page written somewhere else by a
script is not seen until it is sent or opened by a tool this gate watches.

stdlib only. Self-test: test_design_chain_gate.py.
"""
