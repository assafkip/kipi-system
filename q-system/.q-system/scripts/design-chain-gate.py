def is_page(path: str) -> bool:
    p = str(Path(path).resolve()) if path else ""
    if not p or Path(p).suffix.lower() not in PAGE_EXTS:
        return False
    low = p.lower() + "/"
    return not any(m in low for m in INTERNAL_MARKERS)


def _live(p: Path) -> Path:
    """A path inside a held tree this process holds, as the live path it mirrors; any other path
    unchanged. For NAMING only (a refusal points at the live file, the held tree is gone by the
    time it is read) and for telling a held round from a live one. No read goes through it:
    since ASK-1831 every read during a seal is of held bytes."""
    ap = os.path.abspath(p)
    for held in _SNAPSHOTS.values():
        for r in sorted({str(held.root.resolve()), str(held.root)}, key=len, reverse=True):
            if ap == r or ap.startswith(r + os.sep):
                return Path(os.sep + ap[len(r):].lstrip(os.sep))
    return p


def _unheld(text: str) -> str:
    """`text` with every held-tree prefix taken out, so a message names the live path."""
    for held in _SNAPSHOTS.values():
        for r in sorted({str(held.root.resolve()), str(held.root)}, key=len, reverse=True):
            text = text.replace(r, "")
    return text


def find_config(start: Path) -> Path | None:
    """Nearest design-chain.json walking up from the page, then the project dir. Inside a held
    snapshot: the ONE config this seal loaded and gave the producers, never a second walk. The
    chain used to walk the resolved live path and found a config the producers never got: none
    for a relative path (so they measured against their defaults), a looser one through a
    symlink (ASK-1811 review, findings 2 and 3)."""
    held = _held_snapshot(start)
    if held is not None:
        return held.cfg_path
    for d in [start] + list(start.parents):
        c = d / CONFIG_NAME
        if c.is_file():
            return c
    proj = os.environ.get("CLAUDE_PROJECT_DIR")
    if proj and (Path(proj) / CONFIG_NAME).is_file():
        return Path(proj) / CONFIG_NAME
    return None


def load_config(page: Path) -> tuple[dict, Path | None]:
    c = find_config(page.parent)
    if not c:
        return {}, None
    try:
        return json.loads(c.read_text()), c
    except (OSError, ValueError):
        return {}, c


def anchors_from_owners(cfg: dict, cfg_path: Path | None) -> list[tuple[str, str]]:
    """(label, verbatim line) for every anchor, read LIVE from the owner files.
    A missing owner file or an anchor that matches nothing is itself a failure the
    caller reports: the brief cannot quote what does not exist."""
    out = []
    root = cfg_path.parent if cfg_path else Path(".")
    for own in cfg.get("owners", []):
        f = root / own["file"]
        try:
            lines = f.read_text().splitlines()
        except OSError:
            out.append((own["file"], "__MISSING_OWNER_FILE__"))
            continue
        for rx in own.get("anchors", []):
            pat = re.compile(rx)
            hit = None
            for ln in lines:
                m = pat.search(ln)
                if m:
                    # a capture group narrows the anchor to the part that must be
                    # quoted (a rule TITLE, not its 900-character paragraph)
                    hit = m.group(1) if m.groups() else ln
                    break
            out.append((f"{own['file']} :: {rx}", hit.strip() if hit else "__NO_MATCH__"))
    return out


def _held_snapshot(p: Path):
    """The snapshot this process holds whose directory contains `p`, or None. Keyed on the
    snapshot's own directory, never on the live round: producer_problems registers a snapshot
    and then loads the config from the LIVE page, which must still walk the disk."""
    rp = p.resolve()
    for held in _SNAPSHOTS.values():
        sd = held.dir.resolve()
        if rp == sd or sd in rp.parents:
            return held
    return None


def round_dir_for(page: Path) -> Path:
    """The round directory is the nearest ancestor (up to 3 levels) holding brief.md,
    else the page's own directory. Inside a held snapshot it is the snapshot's directory and
    never above it: a round with no brief.md walked out of the snapshot into $TMPDIR, and a
    complete fake round sitting there was what the chain checked (ASK-1811 review, finding-1)."""
    held = _held_snapshot(page)
    if held is not None:
        return held.dir
    for d in [page.parent, page.parent.parent, page.parent.parent.parent]:
        if (d / "brief.md").is_file():
            return d
    return page.parent


# ---------------------------------------------------------------- the chain check

def copied_brief_problems(rd: Path) -> list[str]:
    """A brief that is a byte-copy of an earlier round's brief is a round that never read
    the owners.

    Step 1 of the command is "read the owners, in full, this session", and step 2 is to
    write a brief quoting them. The anchor check proves the brief CONTAINS the quotes; it
    cannot tell a brief that was written from one that was `cp`'d. Measured 2026-09-15:
    five consecutive rounds carried the identical brief, sha c3b247f7b6, so four of them
    did step 1 by copying a file.

    Writing the brief IS the act of reading. Copying it is the act of not reading, and it
    is the one part of that a checksum can see.
    """
    bp = rd / "brief.md"
    if not bp.is_file():
        return []
    mine = sha(bp)
    here = rd.resolve()
    for other in sorted(p for p in here.parent.iterdir() if p.is_dir() and p.resolve() != here):
        ob = other / "brief.md"
        if ob.is_file() and sha(ob) == mine:
            return [f"brief.md is byte-identical to {other.name}/brief.md. Step 1 is to read "
                    f"the owners in full THIS round; writing the brief is how that happens "
                    f"and copying it is how it does not. Re-read them and write this "
                    f"round's brief, even if much of it lands the same."]
    return []


def disposition_problems(rd: Path) -> list[str]:
    """Every weakness the critique names must carry an answer before the round seals.

    HONEST BOUNDARY, stated because this repo has been burned by gates that imply more
    than they check: this sees the marker `WEAK[tag]` and nothing else. A weakness written
    in prose ("this is the risk", "I have not yet tried") is invisible to it, and that is
    not a TODO -- deciding that a sentence describes a weakness is a judgment no regex
    makes. What it does close is the specific hole measured on 2026-09-15: an author who
    DOES mark a finding weak can no longer seal without saying what happened to it.
    """
    cp = rd / "critique.md"
    if not cp.is_file():
        return []
    text = cp.read_text()
    probs: list[str] = []
    # Findings are RAISED above the dispositions section and DISCUSSED inside it. Scanning
    # the whole file counted the section's own explanation of the marker as a new untagged
    # finding, which is a check firing on its own documentation.
    head = re.split(r"^##+\s*Disposition", text, maxsplit=1, flags=re.M | re.I)[0]
    tags, untagged = [], 0
    for m in WEAK_RE.finditer(head):
        # the file's own instructions explain the marker; that mention is not a finding
        line = head[head.rfind("\n", 0, m.start()) + 1: head.find("\n", m.end())]
        if "are marked WEAK" in line or "WEAK_RE" in line:
            continue
        if m.group(1):
            tags.append(m.group(1))
        else:
            untagged += 1
    if untagged:
        probs.append(f"critique.md marks {untagged} finding(s) WEAK with no tag. Write "
                     f"WEAK[some-tag] so the disposition below can answer it by name.")
    # founder questions: raised in a round, registered in ONE ledger he can read
    asks = sorted({m.group(1) for m in FOUNDER_RE.finditer(head)})
    if asks:
        ledger = rd.parent / OPEN_DECISIONS
        have = ledger.read_text() if ledger.is_file() else ""
        missing = [t for t in asks if t not in have]
        if missing:
            probs.append(
                f"critique.md raises founder question(s) {missing} that are not in "
                f"{ledger}. A question written into a round and nowhere else is a question "
                f"he never sees. Add each to the ledger with what is being asked and what "
                f"is blocked until he answers.")

    disposed = {m.group(1): (m.group(2), m.group(3).strip()) for m in DISPOSITION_RE.finditer(text)}
    for t in tags:
        if t not in disposed:
            probs.append(f"critique.md: weakness '{t}' has no disposition. Add a line "
                         f"'- {t}: FIXED <what changed> | DEFERRED <why> | CARRIED <where>'. "
                         f"A weakness you wrote down and shipped anyway is the failure this "
                         f"check exists for.")
        elif not disposed[t][1]:
            probs.append(f"critique.md: weakness '{t}' is marked {disposed[t][0]} with no "
                         f"reason. The disposition says what happened, not just that "
                         f"something did.")
    return probs


def craft_problems(rd: Path, page: Path, cfg: dict, cfg_path: Path | None) -> list[str]:
    """The bar-check. Silent unless the instance declares a `craft` block, so an
    instance that has not opted in keeps exactly the behaviour it had.

    It never certifies a page as good, and deliberately has no success message. Green
    here means ONLY "not a wireframe"; the founder's eye and five real buyer
    conversations are the bar (site-design.md section 8). That posture is borrowed
    whole from cole-gtm's check_technique_parity.py, whose docstring carries the
    founder line this all rests on: "when you have a floor, you are programmed to only
    pass the floor."
    """
    craft = cfg.get("craft") or {}
    if not craft:
        return []
    # An undeclared tier is the REQUIRED tier, never the cheap one: silence must not be
    # the easiest way out (the RCA's cause #4, effort-economy toward the cheapest pass).
    if craft.get("tier", "craft") == "wireframe":
        return []

    probs: list[str] = []
    mpath = rd / CRAFT_MANIFEST

    # A ROUND may declare itself a wireframe round, which the instance default must not
    # be flipped to do. Without this the only way to keep an honest copy-test round
    # sealed is to set craft.tier=wireframe in design-chain.json, which silently lowers
    # the bar for every future round -- the opposite of the point. A round-local
    # declaration is narrow, dated by its own directory, and has to carry a reason, so
    # it reads as a labelled exception rather than a quiet downgrade.
    if mpath.is_file():
        try:
            declared = json.loads(mpath.read_text())
        except ValueError:
            declared = {}
        # A WITHDRAWN round is one the founder has already rejected. This gate exists to
        # stop unfinished work being SHOWN, and a withdrawn round is never going to be
        # shown, so holding it to the bar only forces its author to either fake a receipt
        # or stay stuck. It still carries a reason, and it is one-way: nothing here lets a
        # round be withdrawn and then presented, because presenting it would mean writing
        # it back to a live tier in the open.
        if declared.get("status") == "withdrawn":
            if not str(declared.get("reason", "")).strip():
                return [f"{CRAFT_MANIFEST} declares status 'withdrawn' with no reason. A "
                        f"round may be withdrawn, but the record says why."]
            return []
        if declared.get("tier") == "wireframe":
            if not str(declared.get("reason", "")).strip():
                return [f"{CRAFT_MANIFEST} declares tier 'wireframe' with no reason. A "
                        f"round may opt out of the craft bar, but it says why, in "
                        f"writing, in the round."]
            return []
    if craft.get("require_craft_manifest"):
        if not mpath.is_file():
            probs.append(
                f"missing {mpath}: at tier '{craft.get('tier', 'craft')}' each direction "
                f"declares its signature moment and the technique that realizes it "
                f"(id, technique, role, reference, import[], applied[]). Without it the "
                f"research is decorative and the cheapest layout wins.")
        else:
            try:
                man = json.loads(mpath.read_text())
            except ValueError as e:
                man, probs = {}, probs + [f"{CRAFT_MANIFEST} is not valid JSON: {e}"]
            techs = man.get("techniques") or []
            if not techs:
                probs.append(f"{CRAFT_MANIFEST} declares no techniques, so nothing was "
                             f"verified. Declaring nothing must not be the cheapest way "
                             f"to comply.")
            else:
                src = page.read_text(errors="replace")
                src = re.sub(r"<!--.*?-->", " ", src, flags=re.DOTALL)
                src = re.sub(r"/\*.*?\*/", " ", src, flags=re.DOTALL)
                for t in techs:
                    if t.get("pages") and page.name not in t["pages"]:
                        continue
                    imp, app = t.get("import") or [], t.get("applied") or []
                    if not imp and not app:
                        probs.append(f"{CRAFT_MANIFEST}: technique "
                                     f"'{t.get('id', '?')}' declares no fingerprint, so it "
                                     f"cannot be verified present")
                        continue
                    missing = [p for p in imp + app if not re.search(p, src)]
                    if missing:
                        probs.append(f"{CRAFT_MANIFEST}: technique '{t.get('id', '?')}' "
                                     f"({t.get('role', '?')}) is declared but absent from "
                                     f"{page.name}: {missing}")
    # GROUNDING. The chain had an enforcement half and no input half: the manifest made
    # the build prove it used what it declared, and nothing made the declaration come from
    # anywhere but the builder's own prior. So it verified that the builder built what he
    # imagined, and passed while producing the same generic page three rounds running.
    # Founder, 2026-09-15: "This is the most generic stuff ever... do you need an example
    # to work from?" cole-gtm's design-room had the step and only its back half was ported:
    #   theirs:  ground -> teardown -> steal-manifest -> build -> parity
    #   ported:                     craft-manifest -> build -> parity
    ground = craft.get("require_grounding")
    if ground and mpath.is_file():
        tpath = (cfg_path.parent / ground) if cfg_path else Path(ground)
        if not tpath.is_file():
            probs.append(f"missing {tpath}: at tier '{craft.get('tier','craft')}' the craft "
                         f"manifest must be filled from real pages that were opened, not "
                         f"from memory. Load the references, record what makes each one "
                         f"not generic, then declare techniques that cite them.")
        else:
            teardown = tpath.read_text()
            # Every exemplar the founder has named must appear in the narrative. Founder,
            # 2026-09-15: "you should do that every time I put in more exemplars." Adding
            # a site and not re-reading the GROUP is the forgettable step, so it is a
            # blocked state instead of a promise.
            roster = tpath.parent / "exemplars.json"
            if roster.is_file():
                try:
                    named = [e.get("url", "") for e in
                             json.loads(roster.read_text()).get("exemplars", [])]
                except ValueError:
                    named = []
                host = lambda u: u.split("//")[-1].split("/")[0].lower().removeprefix("www.")
                stale = [u for u in named if host(u) and host(u) not in _norm(teardown)]
                if stale:
                    probs.append(
                        f"{tpath.name} does not read the whole exemplar set: {stale} "
                        f"{'is' if len(stale) == 1 else 'are'} in {roster.name} and absent "
                        f"from the narrative. A new exemplar changes what the others mean, "
                        f"so the group gets re-read, not appended to.")
            try:
                man = json.loads(mpath.read_text())
            except ValueError:
                man = {}
            for t in man.get("techniques") or []:
                ref = str(t.get("reference", "")).strip()
                if not ref:
                    probs.append(f"{CRAFT_MANIFEST}: technique '{t.get('id','?')}' cites no "
                                 f"reference. A technique with no source is invention.")
                elif not any(_norm(part) and _norm(part) in _norm(teardown)
                             for part in re.split(r"[+,]", ref)):
                    probs.append(f"{CRAFT_MANIFEST}: technique '{t.get('id','?')}' cites "
                                 f"'{ref}', which is not in {tpath.name}. Tear the reference "
                                 f"down there first, or the citation is decoration.")
    # THE DISTANCE CHECK. Everything above this line, and every other mechanical check in
    # the chain, is a defect-ABSENCE detector. A bland page has no defects, so it passes
    # all of them: measured 2026-09-15, a deliberately bland control page cleared
    # design-standard-check.py, the dogfood_gate tripwire AND the impeccable browser
    # detector in one run whose own control fired (RCA
    # rca-design-chain-passes-bland-2026-09-15.md). Seven rounds drifted the same way while
    # every gate stayed green and the founder's word for the result was "bland".
    #
    # design-gap-check.py is the missing instrument: not "is anything wrong" but "how far
    # is this from the exemplars the founder actually named", with floors derived from
    # their captures rather than chosen. This is the half that makes its verdict block.
    if craft.get("require_gap_check"):
        gp = rd / "checks" / GAP_CHECK
        if not gp.is_file():
            probs.append(
                f"missing {gp}: run design-gap-check.py <round> --url-base <served> --write. "
                f"Every other check here can only find defects, and a page with nothing on "
                f"it has none.")
        else:
            try:
                gap = json.loads(gp.read_text())
            except ValueError as e:
                gap, probs = {}, probs + [f"{GAP_CHECK} is not valid JSON: {e}"]
            ent = (gap.get("pages") or {}).get(page.name)
            if not ent:
                probs.append(f"{GAP_CHECK} has no entry for {page.name}")
            elif ent.get("sha256") != sha(page):
                probs.append(f"{GAP_CHECK} is stale for {page.name}: the page changed after "
                             f"it was measured. Re-run design-gap-check.py.")
            else:
                for axis in ent.get("below_floor") or []:
                    probs.append(f"{page.name} is below the exemplar floor. {axis}")
    if craft.get("require_fresh_brief"):
        probs += copied_brief_problems(rd)
    if craft.get("require_dispositions"):
        probs += disposition_problems(rd)
    if craft.get("require_impeccable"):
        ip = rd / "checks" / IMPECCABLE_CHECK
        if not ip.is_file() or not ip.read_text().strip():
            probs.append(
                f"missing or empty {ip}: run the impeccable detector on the SERVED URL "
                f"(URL mode drives a real browser and resolves computed styles, which is "
                f"the only thing it does that the static tripwire cannot) and include a "
                f"known-slop control, or the zeros mean nothing.")
    return probs


