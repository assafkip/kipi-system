def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo-root", help="override repo root discovery")
    parser.add_argument("--prd-id", help="PRD id; defaults to active PRD state")
    parser.add_argument(
        "--dry-run", action="store_true", help="validate and print planned writes; do not touch disk"
    )
    parser.add_argument(
        "--from-linear",
        metavar="ASK-n",
        help="generate one spec from a Linear issue's Definition of Ready "
             "instead of from an approved PRD",
    )
    parser.add_argument(
        "--linear-json",
        metavar="PATH",
        help="read the --from-linear issue payload from a JSON file "
             "(offline/test transport) instead of calling Linear",
    )
    args = parser.parse_args(argv)

    try:
        repo_root = Path(args.repo_root).resolve() if args.repo_root else None
        cfg = load_config(repo_root, strict=True)
    except ConfigError as exc:
        sys.stderr.write(f"prd-os config error: {exc}\n")
        return 2

    # Branch BEFORE PRD resolution so no pre-existing invocation changes shape.
    # `is not None`, not truthiness: `--from-linear ''` was passed explicitly and
    # must be refused as a bad id, never fall through to the PRD path.
    if args.from_linear is not None:
        if args.prd_id:
            sys.stderr.write(
                "--from-linear and --prd-id are mutually exclusive: a Linear "
                "issue has no parent PRD.\n"
            )
            return 2
        return _split_from_linear(cfg, args)
    if args.linear_json:
        sys.stderr.write("--linear-json requires --from-linear\n")
        return 2

    try:
        prd_id, prd_path = _resolve_prd_path(cfg, args.prd_id)
    except ValueError as exc:
        sys.stderr.write(f"{exc}\n")
        return 2

    text = prd_path.read_text()
    try:
        fm, body_start = _parse_frontmatter(text)
    except ValueError as exc:
        sys.stderr.write(f"{prd_path}: {exc}\n")
        return 2
    status = fm.get("status")
    if status != "approved":
        sys.stderr.write(
            f"refusing to split PRD with status={status!r}. "
            "Only approved PRDs may be split.\n"
        )
        return 2
    parent_prd_id = fm.get("id", prd_id)

    try:
        raw_manifest = _extract_issues_block(text[body_start:])
        entries = _validate_manifest(raw_manifest)
    except ValueError as exc:
        sys.stderr.write(f"{prd_path}: {exc}\n")
        return 2
    if not entries:
        sys.stderr.write(f"{prd_path}: issues manifest is empty; nothing to split\n")
        return 2

    try:
        parent_prd_relpath = str(prd_path.resolve().relative_to(cfg.repo_root))
    except ValueError:
        parent_prd_relpath = str(prd_path)

    planned: list[tuple[Path, str]] = []
    collisions: list[str] = []
    for entry in entries:
        target = cfg.issues_dir / f"{entry['id']}.md"
        # Reuse any existing marker timestamp so reruns stay byte-identical.
        existing_at = _extract_existing_marker_timestamp(target)
        at_iso = existing_at or _now_iso()
        marker = _format_marker(parent_prd_id, entry["finding_id"], at_iso)
        rendered = _render_spec(entry, parent_prd_id, parent_prd_relpath, marker)
        if target.exists():
            existing = target.read_text()
            if existing != rendered:
                collisions.append(str(target))
                continue
            # byte-identical: idempotent re-run, skip
            continue
        planned.append((target, rendered))

    if collisions:
        sys.stderr.write(
            "refusing to clobber existing issue spec(s):\n  - "
            + "\n  - ".join(collisions)
            + "\n"
        )
        return 2

    if args.dry_run:
        print(json.dumps(
            {
                "prd_id": parent_prd_id,
                "would_create": [str(p) for p, _ in planned],
                "skipped_existing_identical": [
                    str(cfg.issues_dir / f"{e['id']}.md")
                    for e in entries
                    if (cfg.issues_dir / f"{e['id']}.md").exists()
                ],
            },
            indent=2,
        ))
        return 0

    cfg.issues_dir.mkdir(parents=True, exist_ok=True)
    created: list[str] = []
    for target, rendered in planned:
        target.write_text(rendered)
        created.append(str(target.relative_to(cfg.repo_root)) if target.is_absolute() else str(target))
    print(json.dumps({"prd_id": parent_prd_id, "created": created}, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
