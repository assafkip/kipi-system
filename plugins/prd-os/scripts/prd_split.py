TEMPLATE_RELPATH = Path(__file__).resolve().parent.parent / "templates" / "issue.md"
ISSUE_ID_RE = re.compile(r"^[a-z0-9][a-z0-9-]*[a-z0-9]$")
REQUIRED_KEYS = ("id", "title", "finding_id", "allowed_files", "required_checks")
REQUIRED_NONEMPTY_LIST_KEYS = ("allowed_files", "required_checks")
OPTIONAL_LIST_KEYS = ("disallowed_files", "required_reviews")
DEFAULT_PRIORITY = "p1"
GATE_LIFECYCLES = {
    "regression",
    "historical-receipt",
    "retired",
    "external",
}

# Provenance marker: identifies a spec as generated by this tool. The
# issue runner rejects specs without a conforming marker. Format must
# match kipi-dsse/issue_runner.py MARKER_RE.
MARKER_RE = re.compile(
    r"<!--\s+generated-by:\s+prd_split\.py\s+"
    r"prd=(?P<prd>\S+)\s+finding=(?P<finding>\S+)\s+at=(?P<at>\S+)\s+-->"
)


def _format_marker(prd_id: str, finding_id: str, at_iso: str) -> str:
    return (
        f"<!-- generated-by: prd_split.py "
        f"prd={prd_id} finding={finding_id} at={at_iso} -->"
    )


def _extract_existing_marker_timestamp(target: Path) -> Optional[str]:
    """Return the `at=` timestamp from an existing spec's marker, if any.

    Used to keep reruns byte-identical: if the target already has a
    well-formed marker, reuse its timestamp rather than stamping `now`.
    """
    if not target.is_file():
        return None
    try:
        text = target.read_text()
    except OSError:
        return None
    # Locate the line after the frontmatter close.
    if not text.startswith("---"):
        return None
    end = text.find("\n---", 3)
    if end == -1:
        return None
    body = text[end + len("\n---"):]
    for line in body.splitlines():
        stripped = line.strip()
        if not stripped:
            continue
        m = MARKER_RE.fullmatch(stripped)
        return m.group("at") if m else None
    return None


def _now_iso() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


