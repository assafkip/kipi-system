def _yaml_list(values: list[str]) -> str:
    """Render a YAML list suitable for the template placeholder.

    Empty list -> ` []` (inline). Non-empty -> newline + two-space indented
    `  - value` lines. The template places this immediately after the key's
    colon, so the leading newline/space is part of the rendered block.
    """
    if not values:
        return " []"
    return "\n" + "\n".join(f"  - {v}" for v in values)


def _render_spec(
    entry: dict,
    parent_prd_id: str,
    parent_prd_relpath: str,
    marker: str,
) -> str:
    template = TEMPLATE_RELPATH.read_text()
    rendered = (
        template.replace("{{id}}", entry["id"])
        .replace("{{title}}", entry["title"])
        .replace("{{priority}}", entry["priority"])
        .replace("{{parent_prd}}", parent_prd_id)
        .replace("{{parent_prd_path}}", parent_prd_relpath)
        .replace("{{allowed_files_yaml}}", _yaml_list(entry["allowed_files"]))
        .replace("{{disallowed_files_yaml}}", _yaml_list(entry["disallowed_files"]))
        .replace("{{required_checks_yaml}}", _yaml_list(entry["required_checks"]))
        .replace("{{required_reviews_yaml}}", _yaml_list(entry["required_reviews"]))
        .replace("{{acceptance}}", entry["acceptance"] or "<!-- fill in -->")
    )
    # Spine contract fields: append to frontmatter (template-independent so
    # old templates keep working).
    extra = []
    if entry.get("invariant"):
        extra.append(f"invariant: {json.dumps(entry['invariant'])}")
    if entry.get("bypass_check"):
        extra.append(f"bypass_check: {json.dumps(entry['bypass_check'])}")
        extra.append(f"gate_lifecycle: {entry['gate_lifecycle']}")
    if entry.get("deletes"):
        extra.append("deletes:" + _yaml_list(entry["deletes"]))
    if entry.get("bypass_exempt"):
        extra.append(f"bypass_exempt: {json.dumps(entry['bypass_exempt'])}")
    deliverables = entry.get("deliverables") or [entry["title"]]
    extra.append(f"deliverables_count: {len(deliverables)}")
    if extra:
        end = rendered.find("\n---", 3)
        rendered = rendered[:end] + "\n" + "\n".join(extra) + rendered[end:]
    boxes = "\n".join(f"- [ ] {d}" for d in deliverables)
    rendered = rendered.rstrip("\n") + (
        "\n\n## Deliverables\n\n"
        "<!-- Check each box when it ships; close refuses until checked count"
        " equals deliverables_count (locked at issue-start). -->\n"
        f"{boxes}\n"
    )
    return _inject_marker(rendered, marker)


def _inject_marker(rendered: str, marker: str) -> str:
    """Insert the marker as the first non-empty line after frontmatter close."""
    if not rendered.startswith("---"):
        # Template is malformed; bail rather than silently emit an unmarked spec.
        raise ValueError("issue template missing frontmatter")
    end = rendered.find("\n---", 3)
    if end == -1:
        raise ValueError("issue template frontmatter not closed")
    # Split at the newline AFTER the closing ---.
    nl_after = rendered.find("\n", end + len("\n---"))
    if nl_after == -1:
        prefix = rendered
        suffix = ""
    else:
        prefix = rendered[: nl_after + 1]
        suffix = rendered[nl_after + 1:]
    return prefix + marker + "\n\n" + suffix.lstrip("\n")


