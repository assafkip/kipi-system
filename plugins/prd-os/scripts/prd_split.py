def _validate_entry(entry: object, index: int, id_re: re.Pattern = ISSUE_ID_RE) -> dict:
    # id_re is a parameter only so the Linear entry point can pass its own
    # (uppercase `ASK-214`) id shape. The default keeps PRD-manifest behaviour
    # byte-identical.
    if not isinstance(entry, dict):
        raise ValueError(f"entry #{index}: must be a JSON object")
    for key in REQUIRED_KEYS:
        if key not in entry:
            raise ValueError(f"entry #{index}: missing required key {key!r}")
    issue_id = entry["id"]
    if not isinstance(issue_id, str) or not id_re.match(issue_id):
        raise ValueError(
            f"entry #{index}: id must match {id_re.pattern!r}; got {issue_id!r}"
        )
    title = entry["title"]
    if not isinstance(title, str) or not title.strip():
        raise ValueError(f"entry #{index}: title must be a non-empty string")
    finding_id = entry["finding_id"]
    if not isinstance(finding_id, str) or not finding_id.strip():
        raise ValueError(
            f"entry #{index}: finding_id must be a non-empty string"
        )
    for key in REQUIRED_NONEMPTY_LIST_KEYS:
        v = entry[key]
        if not isinstance(v, list) or not v:
            raise ValueError(
                f"entry #{index}: {key} must be a non-empty list "
                "(empty list would silently bypass the verification gate)"
            )
        if not all(isinstance(x, str) and x for x in v):
            raise ValueError(
                f"entry #{index}: {key} entries must be non-empty strings"
            )
    for key in OPTIONAL_LIST_KEYS:
        if key in entry:
            v = entry[key]
            if not isinstance(v, list) or not all(isinstance(x, str) and x for x in v):
                raise ValueError(
                    f"entry #{index}: {key} must be a list of non-empty strings"
                )
    priority = entry.get("priority", DEFAULT_PRIORITY)
    if not isinstance(priority, str) or not priority:
        raise ValueError(f"entry #{index}: priority must be a non-empty string")
    acceptance = entry.get("acceptance", "")
    if not isinstance(acceptance, str):
        raise ValueError(f"entry #{index}: acceptance must be a string")
    for key in (
        "invariant",
        "bypass_check",
        "deletes",
        "bypass_exempt",
        "gate_lifecycle",
    ):
        if key in entry and entry[key] is not None:
            if key == "deletes":
                v = entry[key]
                if not isinstance(v, list) or not all(isinstance(x, str) and x for x in v):
                    raise ValueError(f"entry #{index}: deletes must be a list of regex strings")
            elif not isinstance(entry[key], str) or not entry[key].strip():
                raise ValueError(f"entry #{index}: {key} must be a non-empty string")
    gate_lifecycle = entry.get("gate_lifecycle", "historical-receipt")
    if gate_lifecycle not in GATE_LIFECYCLES:
        raise ValueError(
            f"entry #{index}: gate_lifecycle must be one of "
            f"{', '.join(sorted(GATE_LIFECYCLES))}"
        )
    # Deliverable-count lock (prd-fable-discipline-2026-07-04): every generated
    # spec promises an explicit deliverable count; kipi-dsse close refuses
    # until that many boxes are checked. Optional keys: `deliverables` (list of
    # strings) and/or `deliverables_count` (int >= 1); both present must agree.
    deliverables = entry.get("deliverables")
    def _is_single_line(value: str) -> bool:
        # same line-boundary semantics as issue_runner's checkbox counter
        # (str.splitlines covers \n, \r, \u2028 and every other Unicode
        # line boundary); a multi-line value would inject extra checkbox
        # lines into the generated section
        return len(value.splitlines()) == 1

    if deliverables is not None and (
        not isinstance(deliverables, list)
        or not deliverables
        or not all(
            isinstance(d, str) and d.strip() and _is_single_line(d)
            for d in deliverables
        )
    ):
        raise ValueError(
            f"entry #{index}: deliverables must be a non-empty list of "
            "single-line non-empty strings"
        )
    raw_count = entry.get("deliverables_count")
    if raw_count is not None and (
        isinstance(raw_count, bool) or not isinstance(raw_count, int) or raw_count < 1
    ):
        raise ValueError(
            f"entry #{index}: deliverables_count must be an integer >= 1"
        )
    if deliverables is not None and raw_count is not None and raw_count != len(deliverables):
        raise ValueError(
            f"entry #{index}: deliverables_count ({raw_count}) does not match "
            f"the deliverables list ({len(deliverables)} item(s))"
        )
    if deliverables is not None:
        resolved_deliverables = [d.strip() for d in deliverables]
    elif raw_count is not None:
        resolved_deliverables = [f"deliverable {i + 1}" for i in range(raw_count)]
    else:
        resolved_deliverables = [title.strip()]
    # uniform post-resolution guard: the title fallback goes through the same
    # single-line validation as explicit deliverables (codex adversarial:
    # a multi-line title injected a checked box while count stayed 1)
    if not all(_is_single_line(d) for d in resolved_deliverables):
        raise ValueError(
            f"entry #{index}: a deliverable resolved to a multi-line string "
            "(check the title); single-line only"
        )
    # the counter reads the FIRST column-0 '## Deliverables' section, so
    # free-form acceptance text must not smuggle one in above the generated
    # section (codex adversarial: acceptance hijacked the count)
    if any(
        line.strip().lower().startswith("## deliverables")
        for line in acceptance.splitlines()
    ):
        raise ValueError(
            f"entry #{index}: acceptance must not contain a '## Deliverables' "
            "heading; that section is generated and counted at close"
        )
    _refuse_multi_pr(index, title, acceptance, resolved_deliverables)

    return {
        "id": issue_id,
        "title": title.strip(),
        "finding_id": finding_id.strip(),
        "deliverables": resolved_deliverables,
        "priority": priority,
        "allowed_files": list(entry["allowed_files"]),
        "disallowed_files": list(entry.get("disallowed_files", [])),
        "required_checks": list(entry["required_checks"]),
        "required_reviews": list(entry.get("required_reviews", [])),
        "acceptance": acceptance,
        # Spine contract fields (prd-os-spine-native) — verbatim passthrough
        # into the issue spec so dsse closeout can enforce them.
        "invariant": entry.get("invariant", ""),
        "bypass_check": entry.get("bypass_check", ""),
        "gate_lifecycle": gate_lifecycle,
        "deletes": list(entry.get("deletes", [])),
        "bypass_exempt": entry.get("bypass_exempt", ""),
    }


def _refuse_multi_pr(
    index: int, title: str, acceptance: str, deliverables: list[str]
) -> None:
    """One spec = one deliverable PR (ASK-2541).

    why: RCA token-burn-recurs-after-gate-2026-10-06 root cause #4. A job that
    bundled three PRs, a dry run and a review loop kept one agent alive for 57
    turns, and every waiting turn re-read its whole context. A spec is what an
    agent gets briefed from, so the split has to happen here, before a spec
    exists, not in the agent's head. Same detector as the Agent-brief guard
    (one_job.py), so the two cannot drift. Measured before wiring: 0 of 741
    real manifest entries across four repos trip it.
    """
    reasons = one_job.multi_pr_reasons(
        "\n".join([title, acceptance, *deliverables])
    )
    named = one_job.multi_pr_deliverables(deliverables)
    if named:
        reasons.append(
            f"{len(named)} deliverables each name a PR/branch: "
            + "; ".join(repr(d) for d in named)
        )
    if reasons:
        raise ValueError(
            f"entry #{index}: names more than one deliverable PR ("
            + "; ".join(reasons)
            + "). "
            + one_job.SPLIT_HOWTO
        )


def _validate_manifest(raw: str) -> list[dict]:
    try:
        data = json.loads(raw)
    except json.JSONDecodeError as exc:
        raise ValueError(f"issues manifest is not valid JSON: {exc}") from exc
    if not isinstance(data, list):
        raise ValueError("issues manifest must be a JSON array")
    seen_ids: set[str] = set()
    entries: list[dict] = []
    for i, item in enumerate(data):
        entry = _validate_entry(item, i)
        if entry["id"] in seen_ids:
            raise ValueError(f"duplicate issue id within manifest: {entry['id']!r}")
        seen_ids.add(entry["id"])
        entries.append(entry)
    return entries


